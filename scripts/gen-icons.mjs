// Builds renderer/ui/icons.js from Lucide (ISC, https://github.com/lucide-icons/lucide).
// Usage: LUCIDE_DIR=/path/to/lucide node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = (process.env.LUCIDE_DIR || '../lucide') + '/icons/';
// app icon name -> lucide icon name
const MAP = {
  home: 'house', users: 'users', library: 'library', download: 'download', settings: 'settings', search: 'search',
  back: 'chevron-left', fwd: 'chevron-right', play: 'play', pause: 'pause', vol: 'volume-2', mute: 'volume-x',
  full: 'maximize', exitfull: 'minimize', theater: 'rectangle-horizontal', pip: 'picture-in-picture-2', cc: 'captions', gear: 'settings',
  heart: 'heart', bookmark: 'bookmark', clock: 'clock', plus: 'plus', check: 'check', x: 'x', more: 'ellipsis',
  eyeoff: 'eye-off', ext: 'external-link', refresh: 'refresh-cw', skip: 'skip-forward', sparkle: 'sparkles',
  trash: 'trash', folder: 'folder', palette: 'palette', compass: 'compass', sliders: 'sliders-horizontal',
  music: 'music', shorts: 'clapperboard', msg: 'message-square', queue: 'list-music', listplus: 'list-plus', list: 'list', shuffle: 'shuffle', repeat: 'repeat', repeat1: 'repeat-1',
  prev: 'skip-back', disc: 'disc-3', up: 'chevron-up', down: 'chevron-down', thumbs: 'thumbs-up', reply: 'corner-down-right', globe: 'globe', image: 'image', github: 'github',
  youtube: 'youtube', coffee: 'coffee', lock: 'lock', user: 'user', phone: 'smartphone', folderplus: 'folder-plus', link: 'link', copy: 'copy', pencil: 'pencil', grip: 'grip-vertical', rotate: 'rotate-cw', terminal: 'terminal', droplet: 'droplet',
};
const out = {};
for (const [name, file] of Object.entries(MAP)) {
  const svg = readFileSync(dir + file + '.svg', 'utf8');
  out[name] = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]*?)\s*\/>/g)].map(([, tag, a]) => {
    const attrs = {}; for (const [, k, v] of a.matchAll(/([\w-]+)="([^"]*)"/g)) attrs[k] = v; return [tag, attrs];
  });
}
writeFileSync(new URL('../renderer/ui/icons.js', import.meta.url), `// GENERATED by scripts/gen-icons.mjs from Lucide (ISC license, see assets/licenses/Lucide-ISC.txt). Do not edit by hand.
const D = ${JSON.stringify(out)};
const NS = 'http://www.w3.org/2000/svg', FILLED = new Set(['play', 'pause']);
/** Stroke width comes from the theme (--sw) so each theme can make icons lighter or chunkier. */
export const icon = (name, size = 20) => {
  const s = document.createElementNS(NS, 'svg');
  for (const [k, v] of Object.entries({ viewBox: '0 0 24 24', width: size, height: size, fill: 'none', stroke: 'currentColor', 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true' })) s.setAttribute(k, v);
  s.style.strokeWidth = 'var(--sw, 1.75)';
  for (const [tag, attrs] of D[name] || []) { const e = document.createElementNS(NS, tag); for (const [k, v] of Object.entries(attrs)) e.setAttribute(k, v); if (FILLED.has(name)) e.setAttribute('fill', 'currentColor'); s.append(e); }
  return s;
};
`);
console.log('icons:', Object.keys(out).length, Object.entries(out).filter(([, v]) => !v.length).map(([k]) => k + ' EMPTY'));
